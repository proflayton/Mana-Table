const { test, expect } = require('@playwright/test');
const { launchDesktop } = require('./support/desktop.cjs');

test('strategy review explains real Toph dependencies and persists goals and versioned decisions', async () => {
  const { application } = await launchDesktop('strategy-review');
  try {
    const page = await application.firstWindow(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await expect(page.locator('#loading')).toBeHidden({ timeout: 60000 });
    await page.locator('#import-button').click();
    await page.locator('#import-name').fill('Toph engine review');
    await page.locator('#import-format').selectOption('Commander');
    await page.locator('#import-text').fill('Commander\n1 Toph, the First Metalbender\nDeck\n1 Ashaya, Soul of the Wild\n1 Earthbending Student\n1 Phyrexian Altar\n1 Impact Tremors\n1 Lifecrafter\'s Bestiary\n1 Cloudstone Curio\n1 Mycosynth Lattice\n1 Panharmonicon\n91 Forest');
    await page.locator('#preview-import').click();
    await expect(page.locator('#confirm-import')).toBeEnabled();
    await page.locator('#confirm-import').click();
    await expect(page.locator('#deck-name')).toHaveValue('Toph engine review');
    await page.locator('#strategy-review-open').click();
    const dialog = page.locator('#strategy-review');
    await expect(dialog).toBeVisible();
    await expect(page.locator('#strategy-findings')).toContainText('Lattice switches off Curio');
    await expect(page.locator('#strategy-findings')).toContainText('Panharmonicon can double artifact landfall');
    await page.getByText('Engine dependencies', { exact: true }).click();
    await expect(page.locator('#strategy-engines')).toContainText('earthbends itself again');
    await expect(page.locator('#strategy-engines')).toContainText('All listed pieces are present');
    await page.locator('#strategy-kind').selectOption('artifact-recursion');
    await page.locator('#strategy-pace').selectOption('fast');
    await page.locator('#strategy-plan').fill('Use recurring artifacts and landfall to assemble a sacrifice finish.');
    await page.getByRole('button', { name: 'Save goals', exact: true }).click();
    await expect(page.locator('#strategy-status')).toContainText('Goals saved');
    const swap = page.locator('#strategy-swaps article').filter({ hasText: "Lifecrafter's Bestiary" });
    await expect(swap).toContainText('Ichor Wellspring');
    await expect(swap).toContainText('Tradeoff:');
    await page.locator('#strategy-note').fill('Returning creatures did not trigger my draw engine.');
    await swap.getByRole('button', { name: 'Add to Considering', exact: true }).click();
    await expect(page.locator('#strategy-status')).toContainText('Review saved');
    await expect(page.locator('#strategy-status')).toContainText('Suggested card added to Considering');
    await expect(swap).toContainText('Your decision: consider');
    await page.locator('#strategy-goals > summary').click();
    await page.locator('#strategy-protected').fill("Lifecrafter's Bestiary");
    await page.getByRole('button', { name: 'Save goals', exact: true }).click();
    await expect(page.locator('#strategy-status')).toContainText('Goals saved');
    await expect(swap).toHaveCount(0);
    await page.locator('#strategy-note').fill('Kept a two-land opener; missed land three. One game, on the play.');
    await page.locator('#strategy-observation').click();
    await expect(page.locator('#strategy-status')).toContainText('Review saved');
    await page.getByText('Review history', { exact: true }).click();
    await expect(page.locator('#strategy-history')).toContainText('One game, on the play');
    await page.locator('[data-close-review]').click();
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await expect(page.locator('#strategy-plan')).toHaveValue('Use recurring artifacts and landfall to assemble a sacrifice finish.');
    await expect(page.locator('#strategy-protected')).toHaveValue("Lifecrafter's Bestiary");
    const state = await page.evaluate(() => window.forge.request('snapshot'));
    expect(state.deck.entries.reduce((total, row) => total + row.quantity, 0)).toBe(100);
    expect(state.deck.entries.some(row => row.card.name === 'Ichor Wellspring')).toBe(false);
    for (const [width, height] of [[1000, 740], [1540, 980]]) {
      await application.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows()[0].setSize(...size), [width, height]);
      await dialog.evaluate(element => { element.scrollTop = 0; });
      await expect.poll(() => dialog.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true);
      await page.screenshot({ path: test.info().outputPath(`strategy-review-${width}.png`) });
    }
    await page.locator('[data-close-review]').click();
    await page.locator('#deck-name').fill('Toph renamed without changing cards');
    await page.locator('#deck-name').press('Enter');
    await expect(page.locator('#save-status')).toHaveText('✓ Saved');
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await expect(page.locator('#strategy-history')).not.toContainText('Earlier deck version');
    await page.locator('[data-close-review]').click();
    const forestCopies = page.getByRole('spinbutton', { name: 'Copies of Forest', exact: true });
    await forestCopies.fill('90');
    await forestCopies.press('Enter');
    await expect(forestCopies).toHaveValue('90');
    await expect(page.locator('#deck-size')).toHaveText('99 / 100 including commander');
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await expect(page.locator('#strategy-history')).toContainText('Earlier deck version');
    await page.locator('[data-close-review]').click();
    await page.locator('#undo').click();
    await expect(forestCopies).toHaveValue('91');
    await expect(page.locator('#deck-size')).toHaveText('100 / 100 including commander');
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await expect(page.locator('#strategy-history')).not.toContainText('Earlier deck version');
    await expect(page.locator('#strategy-history')).toContainText('One game, on the play');
    await page.locator('[data-close-review]').click();
    await page.locator('#import-button').click();
    await page.locator('#import-name').fill('Constructed format review');
    await page.locator('#import-format').selectOption('Constructed');
    await page.locator('#import-text').fill('Deck\n1 Cancel\n1 Divination\n58 Island');
    await page.locator('#preview-import').click();
    await expect(page.locator('#confirm-import')).toBeEnabled();
    await page.locator('#confirm-import').click();
    await expect(page.locator('#deck-name')).toHaveValue('Constructed format review');
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await page.locator('#strategy-format').selectOption('Standard');
    await page.locator('#strategy-kind').selectOption('control');
    await page.locator('#strategy-plan').fill('Interact early and refill at instant speed.');
    await page.getByRole('button', { name: 'Save goals', exact: true }).click();
    await expect(page.locator('#strategy-status')).toContainText('Goals saved');
    await expect(page.locator('#strategy-swaps')).not.toContainText('Counterspell');
    await page.locator('[data-close-review]').click();
    await page.locator('#import-button').click();
    await page.locator('#import-name').fill('Limited pool review');
    await page.locator('#import-format').selectOption('Limited');
    await page.locator('#import-text').fill('Deck\n1 Divination\n39 Island');
    await page.locator('#preview-import').click();
    await expect(page.locator('#confirm-import')).toBeEnabled();
    await page.locator('#confirm-import').click();
    await expect(page.locator('#deck-name')).toHaveValue('Limited pool review');
    await page.locator('#strategy-review-open').click();
    await expect(page.locator('#strategy-status')).toContainText('Review updated');
    await expect(page.locator('#strategy-findings')).toContainText('Add your draft or sealed pool');
    await expect(page.locator('#strategy-swaps article')).toHaveCount(0);
    await page.locator('#strategy-pool').fill('Quick Study');
    await page.getByRole('button', { name: 'Save goals', exact: true }).click();
    await expect(page.locator('#strategy-status')).toContainText('Goals saved');
    await expect(page.locator('#strategy-swaps')).toContainText('Quick Study');
    expect(errors).toEqual([]);
  } finally { await application.close(); }
});
