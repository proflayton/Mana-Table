const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { create, verify } = require('../ci-engine-artifact.cjs');
test('shared engine artifacts reject stale source, changed bytes, incomplete manifests and wrong checkouts', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'mana-ci-artifact-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const jar = path.join(dir, 'forge-engine.jar'), fixture = path.join(dir, 'forge-engine-fixtures.jar'), manifest = path.join(dir, 'manifest.json');
  const revision = 'a'.repeat(40), other = 'b'.repeat(40);
  fs.writeFileSync(jar, 'verified engine bytes');
  fs.writeFileSync(fixture, 'verified fixture launcher bytes');
  const record = await create(jar, fixture, manifest, revision, revision);
  assert.deepEqual(await verify(jar, fixture, manifest, revision, revision), record);
  await assert.rejects(verify(jar, fixture, manifest, other, other), /another source/);
  await assert.rejects(verify(jar, fixture, manifest, revision, other), /Checkout/);
  await assert.rejects(create(jar, fixture, path.join(dir, 'wrong.json'), revision, other), /Checkout/);
  fs.appendFileSync(jar, '!');
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /Engine artifact bytes differ/);
  fs.writeFileSync(jar, 'verified engine bytes');
  fs.appendFileSync(fixture, '!');
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /Fixture launcher bytes differ/);
  fs.writeFileSync(fixture, 'verified fixture launcher bytes');
  fs.writeFileSync(manifest, JSON.stringify({ ...record, schemaVersion: 1 }));
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /verification schema/);
  fs.writeFileSync(manifest, JSON.stringify({ ...record, fixtureLauncher: null }));
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /Fixture launcher bytes differ/);
  fs.unlinkSync(fixture);
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /ENOENT/);
  fs.writeFileSync(fixture, '');
  await assert.rejects(create(jar, fixture, path.join(dir, 'empty-fixture.json'), revision, revision), /nonempty regular file/);
  fs.writeFileSync(manifest, '{}');
  await assert.rejects(verify(jar, fixture, manifest, revision, revision), /another source/);
  fs.writeFileSync(jar, '');
  await assert.rejects(create(jar, fixture, path.join(dir, 'empty.json'), revision, revision), /nonempty regular file/);
});
